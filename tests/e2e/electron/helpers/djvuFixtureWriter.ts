function padEven(length: number) {
    return length + (length % 2);
}

function writeUint24BE(target: number[], value: number) {
    target.push((value >>> 16) & 0xff, (value >>> 8) & 0xff, value & 0xff);
}

function writeUint16BE(target: number[], value: number) {
    target.push((value >>> 8) & 0xff, value & 0xff);
}

interface IPreparedZone {
    type: IDjvuFixtureTextZone['type'];
    xmin: number;
    ymin: number;
    xmax: number;
    ymax: number;
    textStart: number;
    textLength: number;
    children: IPreparedZone[];
}

function buildZoneTextAndOffsets(
    zone: IDjvuFixtureTextZone,
    utf8Chunks: Buffer[],
    cursor: {bytes: number},
    trailingSeparator = '',
): IPreparedZone {
    const start = cursor.bytes;
    const children: IPreparedZone[] = [];
    if (zone.children && zone.children.length > 0) {
        for (let index = 0; index < zone.children.length; index += 1) {
            const child = zone.children[index]!;
            const isLast = index === zone.children.length - 1;
            const childSep = isLast ? '' : (ZONE_SEPARATOR[child.type] ?? '');
            const prepared = buildZoneTextAndOffsets(child, utf8Chunks, cursor, childSep);
            children.push(prepared);
        }
        if (trailingSeparator) {
            const sepBuf = Buffer.from(trailingSeparator, 'utf8');
            utf8Chunks.push(sepBuf);
            cursor.bytes += sepBuf.byteLength;
        }
    } else if (zone.text) {
        const textBuf = Buffer.from(zone.text + trailingSeparator, 'utf8');
        utf8Chunks.push(textBuf);
        cursor.bytes += textBuf.byteLength;
    } else if (trailingSeparator) {
        const sepBuf = Buffer.from(trailingSeparator, 'utf8');
        utf8Chunks.push(sepBuf);
        cursor.bytes += sepBuf.byteLength;
    }
    return {
        type: zone.type,
        xmin: zone.xmin,
        ymin: zone.ymin,
        xmax: zone.xmax,
        ymax: zone.ymax,
        textStart: start,
        textLength: cursor.bytes - start,
        children,
    };
}

function encodeZoneBinary(zone: IPreparedZone, parent: IPreparedZone | null, prev: IPreparedZone | null, out: number[]) {
    out.push(ZONE_TYPE_CODE[zone.type]);

    let x = zone.xmin;
    let y = zone.ymin;
    const width = zone.xmax - zone.xmin;
    const height = zone.ymax - zone.ymin;
    let textStartDelta = zone.textStart;

    if (prev) {
        if (zone.type === 'page' || zone.type === 'paragraph' || zone.type === 'line') {
            x = zone.xmin - prev.xmin;
            y = prev.ymin - zone.ymax;
        } else {
            x = zone.xmin - prev.xmax;
            y = zone.ymin - prev.ymin;
        }
        textStartDelta = zone.textStart - (prev.textStart + prev.textLength);
    } else if (parent) {
        x = zone.xmin - parent.xmin;
        y = parent.ymax - zone.ymax;
        textStartDelta = zone.textStart - parent.textStart;
    }

    writeUint16BE(out, (x + 0x8000) & 0xffff);
    writeUint16BE(out, (y + 0x8000) & 0xffff);
    writeUint16BE(out, (width + 0x8000) & 0xffff);
    writeUint16BE(out, (height + 0x8000) & 0xffff);
    writeUint16BE(out, (textStartDelta + 0x8000) & 0xffff);
    writeUint24BE(out, zone.textLength);
    writeUint24BE(out, zone.children.length);

    let prevChild: IPreparedZone | null = null;
    for (const child of zone.children) {
        encodeZoneBinary(child, zone, prevChild, out);
        prevChild = child;
    }
}

/** Encode a DjVu `TXTa` chunk (8-byte IFF header + uncompressed DjVuText payload, even-padded). */
export function encodeDjvuTxtaChunk(root: IDjvuFixtureTextZone): Buffer {
    const utf8Chunks: Buffer[] = [];
    const cursor = {bytes: 0};
    const prepared = buildZoneTextAndOffsets(root, utf8Chunks, cursor);
    const textBuf = Buffer.concat(utf8Chunks);

    const payloadPrefix: number[] = [];
    writeUint24BE(payloadPrefix, textBuf.byteLength);

    const zoneBytes: number[] = [1]; // DjVuText::version = 1
    encodeZoneBinary(prepared, null, null, zoneBytes);

    const payload = Buffer.concat([Buffer.from(payloadPrefix), textBuf, Buffer.from(zoneBytes)]);
    const paddedLen = padEven(payload.byteLength);
    const chunk = Buffer.alloc(8 + paddedLen);
    chunk.write('TXTa', 0, 'ascii');
    chunk.writeUInt32BE(payload.byteLength, 4);
    payload.copy(chunk, 8);
    return chunk;
}

function assertDjvuContainer(bytes: Buffer) {
    if (bytes.byteLength < 16 || bytes.toString('ascii', 0, 4) !== 'AT&T' || bytes.toString('ascii', 4, 8) !== 'FORM') {
        throw new Error('Expected an AT&T FORM DjVu document');
    }
}

/** Insert or replace the `NAVM` outline chunk in a bundled or indirect `FORM:DJVM` file. */
export function setDjvuNavmChunkInFile(filePath: string, navmChunk: Buffer) {
    const source = readFileSync(filePath);
    assertDjvuContainer(source);
    if (source.toString('ascii', 12, 16) !== 'DJVM') {
        throw new Error(`Expected FORM:DJVM document for NAVM injection: ${filePath}`);
    }
    if (source.toString('ascii', 16, 20) !== 'DIRM') {
        throw new Error(`Expected DIRM chunk at offset 16: ${filePath}`);
    }
    const dirmLen = source.readUInt32BE(20);
    const dirmEnd = 24 + padEven(dirmLen);
    const isBundled = (source[24]! & 0x80) !== 0;
    const nfiles = source.readUInt16BE(25);

    let afterNavmOffset = dirmEnd;
    if (dirmEnd + 8 <= source.byteLength && source.toString('ascii', dirmEnd, dirmEnd + 4) === 'NAVM') {
        const oldNavmLen = source.readUInt32BE(dirmEnd + 4);
        afterNavmOffset = dirmEnd + 8 + padEven(oldNavmLen);
    }

    const paddedNavm = navmChunk.byteLength % 2 === 0 ? navmChunk : Buffer.concat([navmChunk, Buffer.alloc(1)]);
    const oldNavmSectionLen = afterNavmOffset - dirmEnd;
    const delta = paddedNavm.byteLength - oldNavmSectionLen;

    const prefix =
        source.byteLength < dirmEnd ? Buffer.concat([source, Buffer.alloc(dirmEnd - source.byteLength)]) : source.subarray(0, dirmEnd);
    const tail = afterNavmOffset < source.byteLength ? source.subarray(afterNavmOffset) : Buffer.alloc(0);

    const updated = Buffer.concat([prefix, paddedNavm, tail]);
    updated.writeUInt32BE(updated.byteLength - 12, 8);

    if (isBundled && delta !== 0) {
        for (let index = 0; index < nfiles; index += 1) {
            const offsetPos = 27 + index * 4;
            const prevOffset = updated.readUInt32BE(offsetPos);
            updated.writeUInt32BE(prevOffset + delta, offsetPos);
        }
    }

    writeFileSync(filePath, updated);
}

/** Append a `TXTa` text layer chunk to a 1-based page inside a bundled `FORM:DJVM` or single-page `FORM:DJVU` file. */
export function setDjvuPageTextInFile(filePath: string, pageNumber: number, root: IDjvuFixtureTextZone) {
    const source = readFileSync(filePath);
    assertDjvuContainer(source);
    const txtaChunk = encodeDjvuTxtaChunk(root);
    const formType = source.toString('ascii', 12, 16);

    if (formType === 'DJVU') {
        if (pageNumber !== 1) {
            throw new Error(`Single-page DjVu has no page ${pageNumber}`);
        }
        const paddedSource = source.byteLength % 2 === 0 ? source : Buffer.concat([source, Buffer.alloc(1)]);
        const updated = Buffer.concat([paddedSource, txtaChunk]);
        updated.writeUInt32BE(updated.byteLength - 12, 8);
        writeFileSync(filePath, updated);
        return;
    }

    if (formType !== 'DJVM' || source.toString('ascii', 16, 20) !== 'DIRM') {
        throw new Error(`Unsupported DjVu container for TXTa injection: ${filePath}`);
    }
    const isBundled = (source[24]! & 0x80) !== 0;
    if (!isBundled) {
        throw new Error(`Expected bundled FORM:DJVM for page text injection: ${filePath}`);
    }
    const nfiles = source.readUInt16BE(25);
    let currentPage = 0;
    let targetComponentIndex = -1;
    let targetOffset = -1;
    let targetFormLen = -1;

    for (let index = 0; index < nfiles; index += 1) {
        const compOffset = source.readUInt32BE(27 + index * 4);
        if (
            compOffset + 12 <= source.byteLength &&
            source.toString('ascii', compOffset, compOffset + 4) === 'FORM' &&
            source.toString('ascii', compOffset + 8, compOffset + 12) === 'DJVU'
        ) {
            currentPage += 1;
            if (currentPage === pageNumber) {
                targetComponentIndex = index;
                targetOffset = compOffset;
                targetFormLen = source.readUInt32BE(compOffset + 4);
                break;
            }
        }
    }

    if (targetComponentIndex < 0 || targetOffset < 0 || targetFormLen < 0) {
        throw new Error(`Page ${pageNumber} not found in bundled DjVu: ${filePath}`);
    }

    const paddedFormEnd = targetOffset + 8 + padEven(targetFormLen);
    const padInsidePage = targetFormLen % 2;
    const newPageFormLen = targetFormLen + padInsidePage + txtaChunk.byteLength;
    const insertedBytes = txtaChunk.byteLength;

    const updated = Buffer.concat([source.subarray(0, paddedFormEnd), txtaChunk, source.subarray(paddedFormEnd)]);
    updated.writeUInt32BE(newPageFormLen, targetOffset + 4);
    updated.writeUInt32BE(updated.byteLength - 12, 8);

    for (let index = targetComponentIndex + 1; index < nfiles; index += 1) {
        const offsetPos = 27 + index * 4;
        const prevOffset = updated.readUInt32BE(offsetPos);
        updated.writeUInt32BE(prevOffset + insertedBytes, offsetPos);
    }

    writeFileSync(filePath, updated);
}
