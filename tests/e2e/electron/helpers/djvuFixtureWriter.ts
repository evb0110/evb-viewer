import {readFileSync, writeFileSync} from 'node:fs';

export interface IDjvuFixtureTextZone {
    type: 'page' | 'column' | 'region' | 'paragraph' | 'line' | 'word' | 'char';
    xmin: number;
    ymin: number;
    xmax: number;
    ymax: number;
    text?: string;
    children?: IDjvuFixtureTextZone[];
}

const ZONE_TYPE_CODE: Record<IDjvuFixtureTextZone['type'], number> = {
    page: 1,
    column: 2,
    region: 3,
    paragraph: 4,
    line: 5,
    word: 6,
    char: 7,
};

const ZONE_SEPARATOR: Partial<Record<IDjvuFixtureTextZone['type'], string>> = {
    column: '\x0b',
    region: '\x1d',
    paragraph: '\x1f',
    line: '\n',
    word: ' ',
};

